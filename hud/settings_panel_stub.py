"""Заглушка будущей панели настроек (HUD/GUI).

Это НЕ полная реализация GUI — только явный контракт, чтобы будущая
разработка знала, куда подключаться. Графический интерфейс выходит за рамки
текущей сессии; управление моделями уже работает через консоль
(см. команды 'модели', 'модель добавить', 'голос добавить' в main.py),
и консольный слой использует тот же ``ModelManager``, что и GUI.

Будущий GUI должен:
  * список полей (имя модели, путь к файлу, роль/тир, кнопка "обзор файла");
  * кнопку "сохранить", которая дёргает те же методы ``ModelManager``
    (``register_local_model`` / ``register_voice`` / ``remove_model``),
    что и консольные команды — логика НЕ дублируется.
"""

from __future__ import annotations

from typing import Optional

from core.utils.logger import get_logger

__all__ = ["SettingsPanel"]

log = get_logger(__name__)


class SettingsPanel:
    """Заглушка панели настроек (GUI пока не реализован)."""

    def __init__(self, settings=None) -> None:
        """
        Args:
            settings: объект настроек (для передачи в ModelManager при сохранении).
        """
        self._settings = settings

    def open(self) -> None:
        """Открывает панель настроек.

        В заглушке просто логирует, что GUI не реализован, и направляет
        пользователя к консольным командам, которые уже работают.
        """
        log.warning(
            "GUI ещё не реализован. Используйте консольные команды: "
            "'модели', 'модель добавить', 'голос добавить' (в main.py REPL)."
        )
        print(
            "[SettingsPanel] GUI отсутствует. Эквивалент в консоли (main.py):\n"
            "  модели          — список зарегистрированных моделей/голосов\n"
            "  модель добавить  — интерактивная регистрация локальной GGUF\n"
            "  голос добавить   — интерактивная регистрация голоса Piper\n"
            "  голос тест       — проверка синтеза речи\n"
            "Все эти команды используют core.utils.ModelManager — тот же механизм,\n"
            "который будет вызывать будущий GUI через кнопку 'сохранить'."
        )

    # --- Контракт будущего GUI (пока не реализован) -------------------- #

    def browse_file(self, filter_desc: str = "All files (*.*)") -> Optional[str]:
        """Будущий 'обзор файла' (QFileDialog). В заглушке — None."""
        log.debug("browse_file: не реализовано в заглушке")
        return None

    def save(self) -> None:
        """Будущая кнопка 'сохранить' — должна звать ModelManager. Заглушка."""
        log.debug("save: не реализовано в заглушке (используйте консоль)")
